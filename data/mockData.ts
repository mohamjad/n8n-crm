export function getKPIs() {
  const data = getClientHealthData()
  
  const atRisk = data.filter(a => a.risk_tier === 'At-Risk' || a.risk_tier === 'Critical').length
  const mrrAtRisk = data
    .filter(a => a.risk_tier === 'At-Risk' || a.risk_tier === 'Critical')
    .reduce((sum, a) => sum + a.mrr, 0)
  const trendingDown = data.filter(a => a.last_7d_usage_change < -10).length
  const expansion = data.filter(a => a.expansion_signal).length
  
  return {
    accountsAtRisk: atRisk,
    mrrAtRisk,
    accountsTrendingDown: trendingDown,
    expansionOpportunities: expansion,
  }
}
